-- 99_RESET.SQL — Reset Pharmaceutical Distribution to clean demo state
-- ============================================================================
USE DATABASE PHARMA_DISTRIBUTION;

-- Suspend tasks during demo
ALTER TASK IF EXISTS APP.TASK_INGEST_ORDERS SUSPEND;
ALTER TASK IF EXISTS APP.TASK_GENERATE_REPLENISHMENT SUSPEND;
ALTER TASK IF EXISTS APP.TASK_REFRESH_FORECASTS SUSPEND;

-- Force refresh Dynamic Tables
ALTER DYNAMIC TABLE CURATED.STOCKOUT_RISK REFRESH;
ALTER DYNAMIC TABLE CURATED.DEMAND_TIMESERIES REFRESH;
ALTER DYNAMIC TABLE CURATED.SERVICE_LEVEL_METRICS REFRESH;
ALTER DYNAMIC TABLE CURATED.REPLENISHMENT_SIGNALS REFRESH;

