-- SELECT COUNT(*) FROM PHARMA_DISTRIBUTION.RAW.DEMAND_HISTORY → 1800000
-- SELECT COUNT(*) FROM PHARMA_DISTRIBUTION.CURATED.STOCKOUT_RISK WHERE DAYS_OF_SUPPLY < 7 → ~47

-- Resume tasks
ALTER TASK IF EXISTS APP.TASK_REFRESH_FORECASTS RESUME;
ALTER TASK IF EXISTS APP.TASK_GENERATE_REPLENISHMENT RESUME;
ALTER TASK IF EXISTS APP.TASK_INGEST_ORDERS RESUME;
